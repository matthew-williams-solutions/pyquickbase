"""The `pyquickbase` command."""

import argparse
import os
import sys
import tempfile
from collections.abc import Sequence
from pathlib import Path

import httpx

from ._codegen import HEADER, render
from ._config import ENV_TOKEN
from ._policy import Policy
from ._sync._client import Quickbase
from ._sync._resources import App
from .errors import QuickbaseError

_NEW_FILE_MODE = 0o644


def _tables(app: App, wanted: Sequence[str], *, include_links: bool = False) -> str:
    tables = app.tables()
    if wanted:
        known = {item.id for item in tables} | {item.name for item in tables}
        missing = [name for name in wanted if name not in known]
        if missing:
            raise QuickbaseError(f"App {app.id} has no table {', '.join(map(repr, missing))}.")
        tables = [item for item in tables if item.id in wanted or item.name in wanted]
    return render(
        [(item, app.table(item.id).fields()) for item in tables], include_links=include_links
    )


def _write(path: Path, source: str) -> None:
    """Replace the file in one step, so a failure can't leave half a module."""
    if path.exists() and not path.read_text(encoding="utf-8").startswith(HEADER):
        raise QuickbaseError(f"{path} wasn't generated by this command, so it won't be replaced.")
    # mkstemp makes a file only its owner can read, which is wrong for source code.
    mode = path.stat().st_mode if path.exists() else _NEW_FILE_MODE
    descriptor, temporary = tempfile.mkstemp(dir=path.parent, prefix=f".{path.name}.")
    try:
        # Always the same line endings, so generating on Windows doesn't change every line.
        with os.fdopen(descriptor, "w", encoding="utf-8", newline="\n") as file:
            file.write(source)
        os.chmod(temporary, mode)
        os.replace(temporary, path)
    except BaseException:
        os.unlink(temporary)
        raise


def _codegen(arguments: argparse.Namespace, http_client: httpx.Client | None) -> int:
    with Quickbase.from_env(
        policy=Policy.read_only(), http_client=http_client, token_env=arguments.token_env
    ) as qb:
        source = _tables(
            qb.app(arguments.app), arguments.table, include_links=arguments.include_links
        )
    path = Path(arguments.output)
    if arguments.check:
        if path.exists() and path.read_text(encoding="utf-8") == source:
            return 0
        sys.stderr.write(f"{path} is out of date. Run this command without --check.\n")
        return 1
    _write(path, source)
    return 0


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="pyquickbase")
    commands = parser.add_subparsers(dest="command", required=True)
    codegen = commands.add_parser(
        "codegen",
        help="Generate typed classes from an app's tables.",
        description="Reads QB_REALM and QB_USER_TOKEN from the environment. Only reads from "
        "Quickbase, and the output holds table IDs and field labels, but no realm or token.",
    )
    codegen.add_argument("--app", required=True, help="The app's ID.")
    codegen.add_argument("--output", required=True, help="The Python file to write.")
    codegen.add_argument(
        "--table", action="append", default=[], help="Only this table, by name or ID. Repeatable."
    )
    codegen.add_argument(
        "--token-env",
        default=ENV_TOKEN,
        help="The environment variable holding the token. Use one with the same access as the code "
        "that will use these classes, because fields its role can't see look deleted.",
    )
    codegen.add_argument(
        "--include-links",
        action="store_true",
        help="Include the links Quickbase makes for each relationship, left out by default.",
    )
    codegen.add_argument(
        "--check", action="store_true", help="Change nothing, and fail if the file is out of date."
    )
    return parser


def main(argv: Sequence[str] | None = None, *, http_client: httpx.Client | None = None) -> int:
    arguments = _parser().parse_args(argv)
    try:
        return _codegen(arguments, http_client)
    except (QuickbaseError, OSError) as exc:
        sys.stderr.write(f"error: {exc}\n")
        return 1
