def is_generated_link(field: Field) -> bool:
    """Whether Quickbase made this field for a relationship, as a link for people to click."""
    if field.type == "dblink":
        return True
    return (
        field.mode == "formula"
        and field.type == "url"
        and (_ADD_RECORD_LINK in (field.formula or ""))
    )


def _read_type(field: Field) -> str:
    return _READ_AS_READ_TYPES.get(read_as(field)) or _READ_TYPES.get(field.type, "Any")


def _write_type(field: Field) -> str:
    return _READ_AS_WRITE_TYPES.get(read_as(field)) or _WRITE_TYPES.get(field.type, "Any")


def _column(name: str, field: Field) -> str:
    args = [
        repr(name),
        str(int(field.id)),
        repr(field.type),
        repr(is_writable(field)),
        repr(field.label),
    ]
    if read_as(field):
        args.append(repr(read_as(field)))
    return f"        Column({', '.join(args)}),"


def _words(text: str) -> list[str]:
    folded = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()
    return _WORD.findall(folded)


def _is_reserved(name: str) -> bool:
    return name in _RESERVED_NAMES


def _attribute_name(field: Field) -> str:
    name = "_".join(_words(field.label))[:_MAX_NAME].rstrip("_") or f"field_{field.id}"
    if name[0].isdigit():
        name = f"f_{name}"
    return f"{name}_" if _is_reserved(name) or name in _RESERVED_ATTRIBUTES else name


def _class_name(table: TableInfo) -> str:
    name = "".join(word.capitalize() for word in _words(table.name))[:_MAX_NAME]
    name = name or f"Table{table.id.capitalize()}"
    if name[0].isdigit():
        name = f"T{name}"
    return f"{name}_" if _is_reserved(name) or name in _RESERVED_CLASSES else name


def _unique(name: str, suffix: object, taken: set[str]) -> str:
    """Give the first holder the plain name, and any later one a suffix."""
    if name in taken:
        name = f"{name}_{suffix}"
    while name in taken:
        name = f"{name}_"
    taken.add(name)
    return name


def _attribute_names(fields: Sequence[Field]) -> dict[int, str]:
    """Name fields in ID order, so a new field never takes an existing field's name."""
    names: dict[int, str] = {RECORD_ID_FIELD: "id"}
    taken = {"id"}
    for field in sorted(fields, key=lambda item: item.id):
        if field.id != RECORD_ID_FIELD:
            names[field.id] = _unique(_attribute_name(field), field.id, taken)
    return names


def _render_writer(
    name: str,
    first: str,
    fields: Sequence[Field],
    names: dict[int, str],
    prefix: str,
) -> list[str]:
    writable = [field for field in fields if is_writable(field)]
    params = [f"cls{first}", *(["*"] if writable else [])]
    params += [f"{names[field.id]}: {_write_type(field)} | Unset = UNSET" for field in writable]
    values = [f"{names[field.id]!r}: {names[field.id]}" for field in writable]
    lines = ["    @classmethod", f"    def {name}(", *(f"        {param}," for param in params)]
    lines += [
        "    ) -> Row[Self]:",
        f"        return cls._row({{{prefix}{', '.join(values)}}})",
    ]
    return lines


def _render_table(table: TableInfo, fields: Sequence[Field], taken: set[str]) -> list[str]:
    fields = sorted(fields, key=lambda item: item.id)
    names = _attribute_names(fields)
    class_name = _unique(_class_name(table), table.id, taken)
    helper = _unique(f"{class_name}Fields", table.id, taken)
    lines = [f"class {helper}:", f"    # Fields of table {table.id!r}, for use in queries."]
    lines += [f"    {names[field.id]} = TypedField({int(field.id)})" for field in fields]
    lines += [
        "",
        "",
        "@dataclass(frozen=True, slots=True, kw_only=True, repr=False)",
        f"class {class_name}(TypedRecord):",
        f"    __table_id__: ClassVar[str] = {table.id!r}",
        "    __columns__: ClassVar[tuple[Column, ...]] = (",
    ]
    lines += [_column(names[field.id], field) for field in fields]
    lines += [
        "    )",
        f"    fields: ClassVar[type[{helper}]] = {helper}",
        "",
    ]
    lines += [f"    {names[field.id]}: {_read_type(field)}" for field in fields]
    lines.append("")
    lines += _render_writer("new", "", fields, names, "")
    lines.append("")
    lines += _render_writer("change", ", id: int", fields, names, f"{'id'!r}: id, ")
    return lines


def render(
    tables: Sequence[tuple[TableInfo, Sequence[Field]]], *, include_links: bool = False
) -> str:
    """Return the source of a module with one class per table.

    The links Quickbase makes for each relationship are left out unless `include_links` is set,
    because only people use them, and a query would otherwise fetch them for every record.
    """
    taken: set[str] = set()
    kept = [
        (table, [item for item in fields if include_links or not is_generated_link(item)])
        for table, fields in sorted(tables, key=lambda item: item[0].id)
    ]
    sections = [_render_table(table, fields, taken) for table, fields in kept]
    uses_decimal = any(read_as(item) == "decimal" for _, fields in kept for item in fields)
    lines = [
        HEADER.rstrip("\n"),
        "# fmt: off",
        "# ruff: noqa",
        "import datetime as _dt",
        "from dataclasses import dataclass",
        *(["from decimal import Decimal as _Decimal"] if uses_decimal else []),
        "from typing import Any, ClassVar, Self",
        "",
        "from pyquickbase import (",
        "    UNSET,",
        "    Column,",
        "    FileAttachment,",
        "    FileUpload,",
        "    Row,",
        "    TypedField,",
        "    TypedRecord,",
        "    Unset,",
        "    User,",
        ")",
    ]
    for section in sections:
        lines += ["", "", *section]
    return "\n".join(lines) + "\n"
