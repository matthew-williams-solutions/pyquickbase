"""Turn table schemas into Python source. No network access.

Labels and names come from Quickbase, where anyone who can edit a table can set them to anything,
including text that would be code if pasted into a source file. So labels only ever appear as
`repr()` string literals, and identifiers are built from an ASCII allowlist.
"""

import builtins
import keyword
import re
import unicodedata
from collections.abc import Sequence

from ._models import RECORD_ID_FIELD, Field, TableInfo
from ._typed import is_writable

HEADER = "# Generated by `pyquickbase codegen`. Do not edit.\n"
_MAX_NAME = 60
_WORD = re.compile(r"[a-z0-9]+")
_DATE = "_dt.date | None"
_DATETIME = "_dt.datetime | None"
_NUMBER = "float | None"
# What a query returns for each type, confirmed against the live API. Anything else is `Any`.
_READ_TYPES = {
    "recordid": "int",
    "text": "str",
    "text-multiple-choice": "str",
    "text-multi-line": "str",
    "rich-text": "str",
    "email": "str",
    "url": "str",
    "phone": "str",
    "address": "str",
    "timeofday": "str",
    "numeric": _NUMBER,
    "currency": _NUMBER,
    "rating": _NUMBER,
    "percent": _NUMBER,
    "duration": _NUMBER,
    "date": _DATE,
    "timestamp": _DATETIME,
    "checkbox": "bool",
    "multitext": "list[str]",
    "user": "dict[str, Any] | None",
    "multiuser": "list[dict[str, Any]]",
    "file": "dict[str, Any]",
}
_WRITE_TYPES = {
    **dict.fromkeys(("text", "text-multiple-choice", "text-multi-line", "rich-text"), "str | None"),
    **dict.fromkeys(("email", "url", "phone", "timeofday"), "str | None"),
    **dict.fromkeys(("numeric", "currency", "rating", "percent", "duration"), _NUMBER),
    "date": _DATE,
    "timestamp": _DATETIME,
    "checkbox": "bool | None",
    "multitext": "list[str] | None",
    "file": "FileUpload",
}
_RESERVED_ATTRIBUTES = {"cls", "fields", "new", "change", "from_record"}
_RESERVED_CLASSES = {
    "Any",
    "ClassVar",
    "Column",
    "FileUpload",
    "Row",
    "Self",
    "TypedField",
    "TypedRecord",
    "Unset",
}


def _words(text: str) -> list[str]:
    folded = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode().lower()
    return _WORD.findall(folded)


def _is_reserved(name: str) -> bool:
    return keyword.iskeyword(name) or keyword.issoftkeyword(name) or hasattr(builtins, name)


def _attribute_name(field: Field) -> str:
    name = "_".join(_words(field.label))[:_MAX_NAME].rstrip("_") or f"field_{field.id}"
    if name[0].isdigit():
        name = f"f_{name}"
    return f"{name}_" if _is_reserved(name) or name in _RESERVED_ATTRIBUTES else name


def _class_name(table: TableInfo) -> str:
    name = "".join(word.capitalize() for word in _words(table.name))[:_MAX_NAME]
    name = name or f"Table{table.id.capitalize()}"
    if name[0].isdigit():
        name = f"T{name}"
    return f"{name}_" if _is_reserved(name) or name in _RESERVED_CLASSES else name


def _unique(name: str, suffix: object, taken: set[str]) -> str:
    """Give the first holder the plain name, and any later one a suffix."""
    if name in taken:
        name = f"{name}_{suffix}"
    while name in taken:
        name = f"{name}_"
    taken.add(name)
    return name


def _attribute_names(fields: Sequence[Field]) -> dict[int, str]:
    """Name fields in ID order, so a new field never takes an existing field's name."""
    names: dict[int, str] = {RECORD_ID_FIELD: "id"}
    taken = {"id"}
    for field in sorted(fields, key=lambda item: item.id):
        if field.id != RECORD_ID_FIELD:
            names[field.id] = _unique(_attribute_name(field), field.id, taken)
    return names


def _render_writer(
    name: str,
    first: str,
    fields: Sequence[Field],
    names: dict[int, str],
    prefix: str,
) -> list[str]:
    writable = [field for field in fields if is_writable(field)]
    params = [f"cls{first}", *(["*"] if writable else [])]
    params += [
        f"{names[field.id]}: {_WRITE_TYPES.get(field.type, 'Any')} | Unset = UNSET"
        for field in writable
    ]
    values = [f"{names[field.id]!r}: {names[field.id]}" for field in writable]
    lines = ["    @classmethod", f"    def {name}(", *(f"        {param}," for param in params)]
    lines += [
        "    ) -> Row[Self]:",
        f"        return cls._row({{{prefix}{', '.join(values)}}})",
    ]
    return lines


def _render_table(table: TableInfo, fields: Sequence[Field], taken: set[str]) -> list[str]:
    fields = sorted(fields, key=lambda item: item.id)
    names = _attribute_names(fields)
    class_name = _unique(_class_name(table), table.id, taken)
    helper = _unique(f"{class_name}Fields", table.id, taken)
    lines = [f"class {helper}:", f"    # Fields of table {table.id!r}, for use in queries."]
    lines += [f"    {names[field.id]} = TypedField({int(field.id)})" for field in fields]
    lines += [
        "",
        "",
        "@dataclass(frozen=True, slots=True, kw_only=True, repr=False)",
        f"class {class_name}(TypedRecord):",
        f"    __table_id__: ClassVar[str] = {table.id!r}",
        "    __columns__: ClassVar[tuple[Column, ...]] = (",
    ]
    lines += [
        f"        Column({names[field.id]!r}, {int(field.id)}, {field.type!r}, "
        f"{is_writable(field)!r}, {field.label!r}),"
        for field in fields
    ]
    lines += [
        "    )",
        f"    fields: ClassVar[type[{helper}]] = {helper}",
        "",
    ]
    lines += [f"    {names[field.id]}: {_READ_TYPES.get(field.type, 'Any')}" for field in fields]
    lines.append("")
    lines += _render_writer("new", "", fields, names, "")
    lines.append("")
    lines += _render_writer("change", ", id: int", fields, names, f"{'id'!r}: id, ")
    return lines


def render(tables: Sequence[tuple[TableInfo, Sequence[Field]]]) -> str:
    """Return the source of a module with one class per table."""
    taken: set[str] = set()
    sections = [
        _render_table(table, fields, taken)
        for table, fields in sorted(tables, key=lambda item: item[0].id)
    ]
    lines = [
        HEADER.rstrip("\n"),
        "# fmt: off",
        "# ruff: noqa",
        "import datetime as _dt",
        "from dataclasses import dataclass",
        "from typing import Any, ClassVar, Self",
        "",
        "from pyquickbase import UNSET, Column, FileUpload, Row, TypedField, TypedRecord, Unset",
    ]
    for section in sections:
        lines += ["", "", *section]
    return "\n".join(lines) + "\n"
